  function calc(items) {
    var t = { k:0, p:0, c:0, f:0, g:0 };
    var rows = (items || []).map(function (pair) {
      var name = pair[0], g = pair[1], v = DB[name] || [0,0,0,0];
      var r = { name:name, g:g, k:v[0]*g/100, p:v[1]*g/100, c:v[2]*g/100, f:v[3]*g/100 };
      t.k += r.k; t.p += r.p; t.c += r.c; t.f += r.f; t.g += g;
      return r;
    });
    return { rows: rows, total: t };
  }
